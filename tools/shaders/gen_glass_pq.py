"""Derive app/shaders/liquid_glass_pq_out.pipe from liquid_glass.pipe.

While an HDR video plays, the scanout is Bgr10A2Bt2100Pq (the engine's
evo_agc_runtime_set_hdr_output) and holds BT.2020 PQ code values, so the glass
reads a backdrop in PQ and must write PQ. This variant is liquid_glass with two
changes: the sampled backdrop is turned from PQ into sRGB-like values (SDR white
at 203 nits, ITU-R BT.2408) before the glass does its work, and the result is
turned back into PQ, the way EVO's ui_screen_2d_pq_out does for the OSD.

Generated rather than copied, so a change to the glass reaches both.

    python3 tools/shaders/gen_glass_pq.py && tools/shaders/build.sh liquid_glass_pq_out
"""
from pathlib import Path

SHADERS = Path(__file__).resolve().parents[2] / "app/shaders"
SRC = SHADERS / "liquid_glass.pipe"
DST = SHADERS / "liquid_glass_pq_out.pipe"

HEADER = """; liquid_glass_pq_out - GENERATED by tools/shaders/gen_glass_pq.py from
; liquid_glass.pipe. Edit that file or the generator, not this one.
;
; The glass for the HDR10 scanout: the backdrop is read as PQ, the glass works
; in sRGB-like values (SDR white at 203 nits) and writes PQ.
;
"""

HELPERS = """/* ---- HDR10 scanout (generated by tools/shaders/gen_glass_pq.py) ---- */
const float GRAPHICS_WHITE_NITS = 203.0;   /* ITU-R BT.2408 */

float pq_oetf(float nits) {
    float Y = pow(clamp(nits / 10000.0, 0.0, 1.0), 0.1593017578125);
    return pow((0.8359375 + 18.8515625 * Y) / (1.0 + 18.6875 * Y), 78.84375);
}

float pq_eotf(float e) {
    float p = pow(clamp(e, 0.0, 1.0), 1.0 / 78.84375);
    return 10000.0 * pow(max(p - 0.8359375, 0.0) / (18.8515625 - 18.6875 * p), 1.0 / 0.1593017578125);
}

/* sRGB-authored colour -> BT.2020 PQ code value (as EVO's UI) */
vec3 srgb_to_pq(vec3 c) {
    vec3 lin = pow(clamp(c, 0.0, 1.0), vec3(2.2));
    vec3 bt2020 = vec3(dot(lin, vec3(0.6274, 0.3293, 0.0433)),
                       dot(lin, vec3(0.0691, 0.9195, 0.0114)),
                       dot(lin, vec3(0.0164, 0.0880, 0.8956)));
    vec3 nits = bt2020 * GRAPHICS_WHITE_NITS;
    return vec3(pq_oetf(nits.r), pq_oetf(nits.g), pq_oetf(nits.b));
}

/* The inverse: a PQ backdrop -> sRGB-like, highlights above SDR white clipped
 * (the glass is frosted: it shows the picture softened, not its peaks). */
vec3 pq_to_srgb(vec3 e) {
    vec3 bt2020 = vec3(pq_eotf(e.r), pq_eotf(e.g), pq_eotf(e.b)) / GRAPHICS_WHITE_NITS;
    vec3 lin = vec3(dot(bt2020, vec3( 1.6605, -0.5876, -0.0728)),
                    dot(bt2020, vec3(-0.1246,  1.1329, -0.0083)),
                    dot(bt2020, vec3(-0.0182, -0.1006,  1.1187)));
    return pow(clamp(lin, 0.0, 1.0), vec3(1.0 / 2.2));
}

"""

EDITS = [
    ("layout(location = 0) out vec4 out_color;\n",
     "layout(location = 0) out vec4 out_color;\n\n" + HELPERS),
    ("    col.b = texture(uSource, (px + off + spread) * g.uShape.zw).b;\n",
     "    col.b = texture(uSource, (px + off + spread) * g.uShape.zw).b;\n"
     "    col = pq_to_srgb(col);\n"),
    ("    out_color = vec4(clamp(col, 0.0, 1.0) * a, a);\n",
     "    out_color = vec4(srgb_to_pq(clamp(col, 0.0, 1.0)) * a, a);\n"),
]


def main():
    text = SRC.read_text(encoding="utf-8")
    for old, new in EDITS:
        if text.count(old) != 1:
            raise SystemExit(f"gen_glass_pq: expected one {old.strip()!r} in {SRC.name}")
        text = text.replace(old, new)
    DST.write_text(HEADER + text, encoding="utf-8")
    print(f"wrote {DST.relative_to(SHADERS.parents[1])}")


if __name__ == "__main__":
    main()
